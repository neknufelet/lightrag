"""沒確認的不准往下走 —— 確認清單的煞車。

**為什麼需要它**：2026-08-18 PO 從 Zotero 丟一篇進來，它**一路走到抽取**，
中間沒有任何地方停下來問他。他當場問「這是現在的正常流程對吧」—— 是的，
而那正是問題：確認清單只是擺在旁邊，沒有卡在路上。

PO 2026-08-17 第二條的下半：**確認完的排進抽取，沒確認的等著。**
理由是消音會改變送去抽取的文字，先抽再改要重抽一次，而抽取是整條線最貴的一步。

⚠ 這一層只回答「該不該擋、理由是什麼」，不碰檔案、不動狀態機 ——
所以在 coder 上就驗得完。
"""
from __future__ import annotations

import logging

logger = logging.getLogger(__name__)


def hold_reason(*, pending: int, confirmed: bool) -> str:
    """要不要擋下這份文件。回一句理由；**空字串＝放行**。

    Args:
        pending: 這份文件有幾項要人確認（:func:`pp.confirm.items_from_plan` 的數量）。
        confirmed: 這份文件已經有確認紀錄了嗎。

    ⚠ **理由要說「怎麼往下走」，不是只說「被擋了」。** 只說被擋的話，人得自己猜
    要去哪裡按什麼。這個碼庫記過同型的病：被擋掉的請求沒寫下理由，害人連猜兩次
    都猜錯真因。

    ⚠ **沒有東西要確認的文件永遠不擋。** 多數乾淨的文件本來就沒有待確認項目，
    擋它們等於把整條線停掉。
    """
    if confirmed or pending <= 0:
        return ""
    logger.info("擋下放行：還有 %d 項沒確認", pending)
    return (f"還有 {pending} 項要你確認，確認完才會排進抽取"
            "（先抽再改要重抽一次，那是最貴的一步）")
